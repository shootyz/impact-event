// One-off generator: bakes public/logo.png into the exact icon/logo PNG sizes
// Apple Wallet expects, and writes the results as base64 constants into
// lib/wallet-assets.ts. Kept as true transparent PNGs (not composited onto a
// white tile) — the pass's backgroundColor is white, so transparency already
// gives the same result, without baking in an assumption about the pass's
// background color that would break if it's ever changed again.
//
// Re-run this only if public/logo.png changes:
//   node scripts/generate-wallet-assets.mjs
import sharp from "sharp";
import { writeFileSync } from "fs";

const LOGO_PATH = "public/logo.png";
const TRANSPARENT = { r: 0, g: 0, b: 0, alpha: 0 };

async function makeIcon(px) {
  const pad = Math.round(px * 0.12);
  return sharp(LOGO_PATH)
    .resize(px - pad * 2, px - pad * 2, { fit: "contain", background: TRANSPARENT })
    .extend({ top: pad, bottom: pad, left: pad, right: pad, background: TRANSPARENT })
    .png()
    .toBuffer();
}

async function makeLogo(heightPx) {
  // No left padding — Apple places logo.png flush against the same left
  // margin the field text below it uses, so any left padding baked into the
  // image itself makes the logo look indented relative to that text.
  const widthPx = Math.round(heightPx * 3.1);
  const pad = Math.round(heightPx * 0.1);
  return sharp(LOGO_PATH)
    .resize(widthPx - pad, heightPx - pad * 2, { fit: "contain", position: "left", background: TRANSPARENT })
    .extend({ top: pad, bottom: pad, left: 0, right: pad, background: TRANSPARENT })
    .png()
    .toBuffer();
}

const [icon1x, icon2x, icon3x, logo1x, logo2x, logo3x] = await Promise.all([
  makeIcon(29), makeIcon(58), makeIcon(87),
  makeLogo(50), makeLogo(100), makeLogo(150),
]);

const b64 = (buf) => buf.toString("base64");

const out = `// Generated by scripts/generate-wallet-assets.mjs from public/logo.png — do not
// hand-edit. Re-run that script if the logo changes.
export const WALLET_IMAGES = {
  icon1x: "${b64(icon1x)}",
  icon2x: "${b64(icon2x)}",
  icon3x: "${b64(icon3x)}",
  logo1x: "${b64(logo1x)}",
  logo2x: "${b64(logo2x)}",
  logo3x: "${b64(logo3x)}",
} as const
`;

writeFileSync("lib/wallet-assets.ts", out);
console.log("Wrote lib/wallet-assets.ts");
